// Generates src/lib/icon-data.js from Phosphor Icons (MIT, https://phosphoricons.com).
// Run once with network access: node scripts/gen-icons.mjs
// The output is committed, so the build itself needs no network.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VERSION = "2.1.1";

// Site icon name -> Phosphor icon name.
const MAP = {
  search: "magnifying-glass", sun: "sun", moon: "moon", system: "desktop", heart: "heart",
  download: "download-simple", copy: "copy", shuffle: "shuffle", arrowUpRight: "arrow-up-right",
  lock: "lock-simple", unlock: "lock-simple-open", refresh: "arrows-clockwise", check: "check",
  chevronLeft: "caret-left", chevronRight: "caret-right", chevronDown: "caret-down", x: "x",
  menu: "list", sidebar: "sidebar-simple", globe: "globe", swap: "arrows-left-right",
  external: "arrow-square-out", plus: "plus", trash: "trash", bell: "bell", grid: "squares-four",
  chart: "chart-bar", users: "users", settings: "gear", box: "package", terminal: "terminal-window",
  sparkle: "sparkle", calendar: "calendar-blank", image: "image", palette: "palette", eye: "eye",
  sliders: "sliders-horizontal", bookmark: "bookmark-simple",
  // Sidebar: Indian metaphors where Phosphor has them (lotus, rangoli flower, textile, dawn).
  lotus: "flower-lotus", swatches: "swatches", compass: "compass", dictionary: "book-open-text",
  rangoli: "flower", textile: "t-shirt", dawn: "sun-horizon", scene: "monitor-play",
  brush: "paint-brush-broad", robot: "robot",
  // Links and index.
  github: "github-logo", linkedin: "linkedin-logo", valueIndex: "list-numbers", portfolio: "globe-hemisphere-east", author: "pen-nib",
  book: "book-open", translate: "translate", fileDown: "file-arrow-down", file: "file-text", scales: "scales", flag: "flag",
};

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
const get = async (weight, name) => {
  const file = weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`;
  const res = await fetch(`https://unpkg.com/@phosphor-icons/core@${VERSION}/assets/${weight}/${file}`);
  if (!res.ok) throw new Error(`${res.status} for ${weight}/${file}`);
  return inner(await res.text());
};

const out = {};
for (const [key, name] of Object.entries(MAP)) {
  out[key] = { regular: await get("regular", name), fill: await get("fill", name) };
}

const body = `// Generated by scripts/gen-icons.mjs from Phosphor Icons ${VERSION} (MIT License, https://phosphoricons.com).
// 256px grid, regular and fill weights. Do not edit by hand.
export const PHOSPHOR = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, "src", "lib", "icon-data.js"), body);
console.log(`wrote ${Object.keys(out).length} icons`);
